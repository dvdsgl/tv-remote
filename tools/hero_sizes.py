#!/usr/bin/env python3
"""Writes the hero phone's size rules into docs/index.html (between the hero-sizes markers).

The phone's scale --s is min(--sh, --sw): --sh is what the window height leaves after the
headline and Download button, --sw what the width allows. Both are set by media query
steps, because CSS can't divide one length by another in every browser yet. The phone is
847 units tall and 434 wide at scale 1 (402x820 screen plus bezel)."""
import re, pathlib
PH, PW = 847, 434
def clamp(v, lo=.28, hi=.95): return min(max(v, lo), hi)
def family(cond, extras, wfrac, wrange, hi=.95):
    out = [f"  @media {cond} {{", f"    .hero {{ --sh: .3; --sw: .3; }}"]
    for h in range(360, 1441, 20):
        out.append(f"    @media (min-height: {h}px) {{ .hero {{ --sh: {clamp((h - extras) / PH, hi=hi):.3f}; }} }}")
    for w in range(wrange[0], wrange[1] + 1, 20):
        out.append(f"    @media (min-width: {w}px) {{ .hero {{ --sw: {clamp(w * wfrac / PW, hi=hi):.3f}; }} }}")
    out.append("  }")
    return out
rules = ["  /* hero-sizes:start (generated by tools/hero_sizes.py) */"]
# Portrait: phone, then headline (font 9vw, capped per band), then Download.
rules += family("(orientation: portrait) and (max-width: 439px)", 300, .84, (280, 439))
rules += family("(orientation: portrait) and (min-width: 440px) and (max-width: 599px)", 326, .84, (440, 599))
rules += family("(orientation: portrait) and (min-width: 600px)", 370, .62, (600, 1400))
# Landscape: phone beside the copy, as tall as the window allows.
rules += family("(orientation: landscape)", 64, .40, (480, 2600), hi=.9)
rules.append("  /* hero-sizes:end */")
p = pathlib.Path(__file__).resolve().parent.parent / "docs/index.html"
s = p.read_text()
s = re.sub(r"  /\* hero-sizes:start.*?hero-sizes:end \*/", lambda m: "\n".join(rules), s, flags=re.S)
p.write_text(s)
